#!/usr/bin/env python3
"""Prove that a real task runs through Agent Bridge, and say so honestly.

The IDE showing "backend: connected" proves the two can talk. It does
not prove that anything runs. This drives the same path the interface
drives: create a session, submit a task, watch it run, and read the
outcome and the evidence back.

The point is not the task. The point is the chain. A task that goes
through this is a task that a local model decided on, that the Bridge
executed, and that produced evidence the interface can show.

The result is written as a digest so the claim can be checked later
without running it again.

Usage:
    python tools/prove_ide_task.py
    python tools/prove_ide_task.py --task "write a haiku to haiku.txt"
"""

from __future__ import annotations

import argparse
import json
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "docs" / "evidence" / "ide-task-proof.yaml"

BRIDGE = "http://127.0.0.1:8471"


def request(url: str, payload: dict | None = None, timeout: float = 60.0):
    """Call the Bridge. Returns (status, body)."""
    data = None
    headers = {}
    if payload is not None:
        data = json.dumps(payload).encode("utf-8")
        headers["Content-Type"] = "application/json"
    req = urllib.request.Request(url, data=data, headers=headers,
                                 method="POST" if data else "GET")
    try:
        with urllib.request.urlopen(req, timeout=timeout) as res:
            return res.status, json.loads(res.read().decode("utf-8", "replace"))
    except urllib.error.HTTPError as exc:
        try:
            return exc.code, json.loads(exc.read().decode("utf-8", "replace"))
        except Exception:
            return exc.code, {"error": "unreadable body"}
    except Exception as exc:
        return None, {"error": f"{type(exc).__name__}: {exc}"}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--bridge", default=BRIDGE)
    ap.add_argument("--task", default="write a haiku about a river to haiku.txt")
    ap.add_argument("--workspace", default="")
    ap.add_argument("--timeout", type=float, default=600.0)
    args = ap.parse_args()

    bridge = args.bridge.rstrip("/")
    lines: list[str] = []

    def emit(text: str = "") -> None:
        lines.append(text)
        print(text)

    emit("# A real task through Agent Bridge")
    emit("#")
    emit("# Generated by tools/prove_ide_task.py against the running Bridge.")
    emit("# Every value below was read from the live service.")
    emit(f"generated_at: {time.strftime('%Y-%m-%dT%H:%M:%S%z')}")
    emit(f"bridge: {bridge}")
    emit("")

    status, health = request(f"{bridge}/v1/runtime")
    if status != 200:
        emit("the Bridge did not answer, so nothing was proved")
        emit(f"  status: {status}  {health}")
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return 1
    emit("bridge_state:")
    emit(f"  health: {health.get('health')}")
    emit(f"  models: {len(health.get('models') or [])}")
    emit(f"  active_model: {health.get('active_model') or '(none selected)'}")
    emit("")

    # The same path the interface drives.
    workspace = args.workspace or str(REPO)
    status, session = request(f"{bridge}/v1/sessions", {
        "workspace": workspace,
        "mode": "build",
        "approval": "AUTO_SAFE",
        "interactive": False,
    })
    if not session.get("session_id"):
        emit("the session could not be created")
        emit(f"  status: {status}  {session}")
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return 1
    session_id = session["session_id"]
    emit("session:")
    emit(f"  session_id: {session_id}")
    emit(f"  status: {session.get('status')}")
    emit(f"  interactive: {session.get('interactive')}")
    emit("")

    status, handle = request(f"{bridge}/v1/sessions/{session_id}/tasks",
                             {"text": args.task, "idempotency_key": ""})
    emit("task:")
    emit(f"  objective: {args.task}")
    emit(f"  submit status: {status}")
    task_id = handle.get("task_id") or handle.get("id") or ""
    emit(f"  task_id: {task_id or '(none)'}")
    if not task_id:
        emit(f"  the task was not accepted: {handle}")
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return 1
    emit("")

    # Watch it run.
    deadline = time.time() + args.timeout
    last = {}
    while time.time() < deadline:
        _, last = request(f"{bridge}/v1/sessions/{session_id}")
        state = (last.get("tasks") or {}).get(task_id) or {}
        status_value = str(state.get("status", ""))
        if status_value in ("VERIFIED_COMPLETE", "COMPLETED", "FAILED",
                            "BLOCKED", "CANCELLED"):
            break
        time.sleep(2)

    state = (last.get("tasks") or {}).get(task_id) or {}
    emit("outcome:")
    emit(f"  status: {state.get('status', '(unknown)')}")
    emit(f"  progress_pct: {state.get('progress_pct')}")
    emit(f"  model: {state.get('model') or '(none recorded)'}")
    emit(f"  worker: {state.get('worker') or '(none recorded)'}")
    emit("")

    # Which model actually did the work. The Bridge records it in the
    # session's own state, and the route only carries the status.
    session_state = Path(workspace) / ".bridge" / "sessions" / session_id / "session.json"
    if session_state.is_file():
        try:
            recorded = json.loads(session_state.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            recorded = {}
        roles = recorded.get("models") or {}
        emit("the model that did it:")
        for role in ("planner", "coder", "reviewer", "general"):
            if roles.get(role):
                emit(f"  {role}: {roles[role]}")
        emit(f"  steps taken: {recorded.get('step')}")
        emit(f"  files touched: {recorded.get('files_touched')}")
        emit(f"  errors: {recorded.get('errors')}")
        emit("")

    _, final = request(f"{bridge}/v1/sessions/{session_id}/final")
    emit("final:")
    if isinstance(final, dict):
        for key in ("status", "verified", "summary", "result", "evidence",
                    "approach", "duration_s", "blocked", "gate"):
            if key in final:
                emit(f"  {key}: {str(final[key])[:300]}")
    else:
        emit(f"  {str(final)[:300]}")
    emit("")

    _, evidence = request(f"{bridge}/v1/sessions/{session_id}")
    refs = []
    if isinstance(evidence, dict):
        refs = evidence.get("evidence_refs") or evidence.get("evidence") or []
    emit("evidence:")
    emit(f"  refs: {len(refs)}")
    for ref in refs[:8]:
        emit(f"    - {str(ref)[:200]}")
    emit("")

    # What the task actually left behind. This is the part that cannot be
    # faked: a file on disk, written by a model that decided to write it.
    emit("produced:")
    workspace_path = Path(workspace)
    if workspace_path.is_dir():
        produced = 0
        for path in sorted(workspace_path.rglob("*")):
            if not path.is_file():
                continue
            rel = path.relative_to(workspace_path).as_posix()
            if rel.startswith(".bridge/"):
                # The Bridge's own runtime state: contracts, checkpoints,
                # locks, memory and history. It is recorded as the count of
                # state files rather than listed, because it is the
                # machinery and not the result.
                continue
            produced += 1
            try:
                body = path.read_text(encoding="utf-8", errors="replace")
            except OSError:
                body = ""
            emit(f"  {rel} ({path.stat().st_size} bytes)")
            for line in body.strip().splitlines()[:8]:
                emit(f"      {line}")
        emit(f"  result files: {produced}")
        bridge_state = workspace_path / ".bridge"
        if bridge_state.is_dir():
            runtime_files = sum(1 for p in bridge_state.rglob("*") if p.is_file())
            emit(f"  the Bridge recorded {runtime_files} runtime state file(s)")
    else:
        emit("  the workspace was not there to look at")
    emit("")

    emit("verdict:")
    task_status = str(state.get("status", ""))
    if task_status in ("VERIFIED_COMPLETE", "COMPLETED"):
        emit("  a real task ran through the Bridge, with a model, and produced a result")
    else:
        emit(f"  the task did not complete: it ended as {task_status or '(unknown)'}")
    emit("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nwritten to {OUT}")
    return 0 if task_status in ("VERIFIED_COMPLETE", "COMPLETED") else 1


if __name__ == "__main__":
    sys.exit(main())
