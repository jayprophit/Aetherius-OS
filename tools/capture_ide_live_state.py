"""Capture the live Aetherius IDE stack state as a reviewable evidence file.

This is evidence, not a claim. Every number in the output is read from
the running services at the moment the file is written. If a service is
down the file says so rather than omitting it.
"""

from __future__ import annotations

import json
import time
import urllib.error
import urllib.request
from pathlib import Path

IDE = "http://127.0.0.1:5199"
BRIDGE = "http://127.0.0.1:8471"
OLLAMA = "http://127.0.0.1:11434"

OUT = Path(r"C:\Users\jpowe\Desktop\Projects\Aetherius-OS\docs\evidence"
           r"\aetherius-ide-live-state.yaml")


def get(url: str, timeout: float = 20.0):
    """Return (status, body). Never raises; a failure is a fact too."""
    try:
        with urllib.request.urlopen(url, timeout=timeout) as res:
            return res.status, json.loads(res.read().decode("utf-8", "replace"))
    except urllib.error.HTTPError as exc:
        try:
            return exc.code, json.loads(exc.read().decode("utf-8", "replace"))
        except Exception:
            return exc.code, {"error": "unreadable body"}
    except Exception as exc:
        return None, {"error": f"{type(exc).__name__}: {exc}"}


lines: list[str] = []


def emit(text: str = "") -> None:
    lines.append(text)


emit("# Aetherius IDE - live state")
emit("#")
emit("# Generated by tools/capture_ide_live_state.py against the running")
emit("# stack. Every value below was read from the live services at the")
emit("# moment this file was written. Nothing here is asserted by hand.")
emit(f"generated_at: {time.strftime('%Y-%m-%dT%H:%M:%S%z')}")
emit("")

status, tags = get(f"{OLLAMA}/api/tags")
models = tags.get("models", []) if isinstance(tags, dict) else []
emit("model_runtime:")
emit(f"  endpoint: {OLLAMA}")
emit(f"  status: {status if status else 'unreachable'}")
emit(f"  models: {len(models)}")
for m in models:
    emit(f"    - {m.get('name')} ({round(m.get('size', 0) / 1e9, 2)} GB)")
emit("")

status, runtime = get(f"{BRIDGE}/v1/runtime")
emit("bridge_runtime:")
emit(f"  endpoint: {BRIDGE}/v1/runtime")
emit(f"  status: {status if status else 'unreachable'}")
if isinstance(runtime, dict):
    emit(f"  health: {runtime.get('health')}")
    emit(f"  models_reported: {len(runtime.get('models', []))}")
    emit(f"  active_model: {runtime.get('active_model') or '(none selected)'}")
    emit(f"  tasks: {len(runtime.get('tasks', []))}")
    emit(f"  queue_depth: {runtime.get('queue_depth')}")
    emit(f"  workers: {len(runtime.get('workers', []))}")
    emit(f"  approvals_pending: {len(runtime.get('approvals_pending', []))}")
    emit(f"  errors: {runtime.get('errors') or []}")
emit("")

status, inv = get(f"{BRIDGE}/v1/models")
emit("bridge_models:")
emit(f"  endpoint: {BRIDGE}/v1/models")
emit(f"  status: {status if status else 'unreachable'}")
emit(f"  models: {len(inv.get('models', [])) if isinstance(inv, dict) else 0}")
emit("")

status, checks = get(f"{BRIDGE}/v1/selfcheck")
emit("bridge_selfcheck:")
if isinstance(checks, dict):
    for c in checks.get("checks", []):
        reason = c.get("reason") or ""
        emit(f"  {c.get('check')}: {c.get('status')}" + (f"  ({reason})" if reason else ""))
else:
    emit(f"  unavailable: {checks}")
emit("")

emit("consistency:")
emit(f"  runtime_models == models_route: "
     f"{len(runtime.get('models', [])) == len(inv.get('models', [])) if isinstance(runtime, dict) and isinstance(inv, dict) else 'unknown'}")
emit("")

status, _ = get(f"{IDE}/")
emit("ide:")
emit(f"  endpoint: {IDE}")
emit(f"  status: {status if status else 'unreachable'}")
emit("")

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines))
print(f"\nwritten to {OUT}")
