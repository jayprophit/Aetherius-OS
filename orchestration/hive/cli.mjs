#!/usr/bin/env node
/**
 * Aetherius Hive CLI.
 *
 *   node orchestration/hive/cli.mjs status
 *   node orchestration/hive/cli.mjs register --id hermes --kind hermes --model solar-mini4:free
 *   node orchestration/hive/cli.mjs send --from hermes --to kilo --topic ci "please verify the build"
 *   node orchestration/hive/cli.mjs read --to kilo --since 0
 *   node orchestration/hive/cli.mjs tasks --status open
 *   node orchestration/hive/cli.mjs task add --from supervisor --title "CI green" --priority 1
 *   node orchestration/hive/cli.mjs task claim --id TASK --agent kilo
 *   node orchestration/hive/cli.mjs task update --id TASK --agent kilo --status done --result "3/3 green"
 *   node orchestration/hive/cli.mjs memory set --key release.gate --owner supervisor --value "NOT_RELEASABLE"
 *   node orchestration/hive/cli.mjs work log --agent hermes --task TASK --status done --summary "tests green"
 *   node orchestration/hive/cli.mjs work list --agent hermes --status pending
 *   node orchestration/hive/cli.mjs work summary
 *   node orchestration/hive/cli.mjs listen
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { hive } from "./client.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");

function cell(value) {
  return String(value ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

async function exportWorkLedger(outPath) {
  const [summary, work, tasks] = await Promise.all([
    hive.workSummary(),
    hive.work({ limit: 200 }),
    hive.tasks({ limit: 500 }),
  ]);
  const target = outPath || join(ROOT, "knowledge", "Aetherius-Vault", "Work Ledger.md");
  const lines = [
    "# Work Ledger",
    "",
    "<!-- Generated by orchestration/hive/cli.mjs work export. Do not edit by hand. -->",
    "",
    `Generated: ${summary.generated_at}`,
    "",
    `Total entries: **${summary.totals}** · open or blocked: **${summary.pending}**`,
    "",
    "## By status",
    "",
    "| Status | Count |",
    "| --- | --- |",
    ...summary.by_status.map((row) => `| ${cell(row.status)} | ${row.n} |`),
    "",
    "## Tasks",
    "",
    "| Task status | Count |",
    "| --- | --- |",
    ...summary.tasks.map((row) => `| ${cell(row.status)} | ${row.n} |`),
    "",
    "## Latest per agent",
    "",
    "| Agent | Status | Summary | At |",
    "| --- | --- | --- | --- |",
    ...summary.latest.map(
      (row) => `| ${cell(row.agent)} | ${cell(row.status)} | ${cell(row.summary)} | ${cell(row.ts)} |`
    ),
    "",
    "## Open, pending and blocked tasks",
    "",
    "| Task | Assignee | Status | Priority | Title |",
    "| --- | --- | --- | --- | --- |",
    ...tasks.tasks
      .filter((task) => !["done", "failed"].includes(task.status))
      .map(
        (task) =>
          `| ${cell(task.id)} | ${cell(task.assignee)} | ${cell(task.status)} | ${task.priority} | ${cell(task.title)} |`
      ),
    "",
    "## Recent work",
    "",
    "| Time | Agent | Task | Action | Status | Summary |",
    "| --- | --- | --- | --- | --- | --- |",
    ...work.work.map(
      (row) =>
        `| ${cell(row.ts)} | ${cell(row.agent)} | ${cell(row.task_id)} | ${cell(row.action)} | ${cell(row.status)} | ${cell(row.summary)} |`
    ),
    "",
  ];
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, lines.join("\n"), "utf8");
  return { ok: true, path: target, entries: summary.totals, pending: summary.pending };
}

function parse(argv) {
  const positional = [];
  const flags = {};
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];
    if (token.startsWith("--")) {
      const key = token.slice(2);
      const next = argv[i + 1];
      if (next === undefined || next.startsWith("--")) {
        flags[key] = true;
      } else {
        flags[key] = next;
        i += 1;
      }
    } else {
      positional.push(token);
    }
  }
  return { positional, flags };
}

function print(value) {
  process.stdout.write(`${JSON.stringify(value, null, 2)}\n`);
}

async function main() {
  const [command, subcommand, ...rest] = process.argv.slice(2);
  const { positional, flags } = parse(rest);

  if (!command || command === "help" || command === "--help") {
    console.log(
      "commands: status | register | heartbeat | agents | send | read | tasks | task | memory | work | listen"
    );
    return;
  }

  if (command === "status") return print(await hive.status());

  if (command === "register") {
    return print(
      await hive.register({
        id: flags.id,
        kind: flags.kind || flags.id,
        protocol: flags.protocol,
        model: flags.model,
        status: flags.status || "idle",
        metadata: flags.metadata ? JSON.parse(flags.metadata) : undefined,
      })
    );
  }

  if (command === "heartbeat") {
    return print(await hive.heartbeat(flags.id, { status: flags.status, model: flags.model }));
  }

  if (command === "agents") return print(await hive.agents());

  if (command === "send") {
    return print(
      await hive.send({
        sender: flags.from || "cli",
        recipient: flags.to || "*",
        topic: flags.topic || "general",
        body: positional.join(" ") || flags.body || "",
        correlation_id: flags.correlation,
        reply_to: flags.reply_to ? Number(flags.reply_to) : undefined,
      })
    );
  }

  if (command === "read") {
    return print(
      await hive.messages({
        since: Number(flags.since || 0),
        to: flags.to,
        topic: flags.topic,
        limit: Number(flags.limit || 50),
      })
    );
  }

  if (command === "tasks") {
    return print(await hive.tasks({ status: flags.status, assignee: flags.assignee }));
  }

  if (command === "task") {
    if (subcommand === "add") {
      return print(
        await hive.createTask({
          created_by: flags.from || "cli",
          assignee: flags.assignee,
          title: flags.title || positional.join(" "),
          detail: flags.detail,
          priority: Number(flags.priority || 3),
          files: flags.files ? JSON.parse(flags.files) : undefined,
        })
      );
    }
    if (subcommand === "claim") return print(await hive.claimTask(flags.id, flags.agent));
    if (subcommand === "update") {
      return print(
        await hive.updateTask(flags.id, {
          agent: flags.agent || "cli",
          status: flags.status,
          result: flags.result,
          evidence: flags.evidence,
        })
      );
    }
    if (subcommand === "get") return print(await hive.task(flags.id));
  }

  if (command === "memory") {
    if (subcommand === "get") return print(await hive.memoryGet(flags.key));
    if (subcommand === "set") {
      return print(await hive.memorySet(flags.key, flags.value, flags.owner || "cli", flags.tags ? JSON.parse(flags.tags) : []));
    }
  }

  if (command === "work") {
    if (subcommand === "log" || subcommand === "add") {
      return print(
        await hive.recordWork({
          agent: flags.agent || "cli",
          task_id: flags.task || flags.task_id,
          action: flags.action || "note",
          status: flags.status || "info",
          summary: flags.summary || positional.join(" "),
          files: flags.files ? JSON.parse(flags.files) : undefined,
          evidence: flags.evidence,
          metadata: flags.metadata ? JSON.parse(flags.metadata) : undefined,
        })
      );
    }
    if (subcommand === "list") {
      return print(
        await hive.work({
          agent: flags.agent,
          status: flags.status,
          task_id: flags.task || flags.task_id,
          since: Number(flags.since || 0),
          limit: Number(flags.limit || 100),
        })
      );
    }
    if (subcommand === "summary") return print(await hive.workSummary());
    if (subcommand === "export") return print(await exportWorkLedger(flags.out));
  }

  if (command === "listen") {
    const response = await fetch(`${hive.url}/events`);
    if (!response.ok || !response.body) throw new Error(`cannot open event stream: ${response.status}`);
    const reader = response.body.getReader();
    const decoder = new TextDecoder();
    process.stdout.write(`[hive] listening on ${hive.url}/events\n`);
    for (;;) {
      const { value, done } = await reader.read();
      if (done) break;
      process.stdout.write(decoder.decode(value, { stream: true }));
    }
    return;
  }

  throw new Error(`unknown command: ${command}`);
}

main().catch((error) => {
  console.error(`hive cli: ${error.message}`);
  process.exitCode = 1;
});
