#!/usr/bin/env node
/**
 * Generate the application catalogue from the slices on disk.
 *
 * `apps/` holds 141 directories. The shell and Settings both need one
 * complete, honest list of what exists, what kind of thing it is, and what
 * state its own build manifest declares. This script reads every
 * apps/<dir>/package.json and build.yaml and emits src/apps/catalogue.ts.
 *
 * The output is derived, and a test (src/apps/catalogue.test.ts) fails when
 * the committed file differs from what this script produces — the same
 * pattern the build manifest registry uses. Regenerate with:
 *
 *   node scripts/generate-app-catalogue.mjs
 */

import { readdirSync, readFileSync, statSync, existsSync, writeFileSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const APPS = join(root, "apps");
const OUTPUT = join(root, "src", "apps", "catalogue.ts");

const KIND_BY_DIRECTORY = new Map([
  ["LedgerLands", "product"],
  ["Poietek", "product"],
  ["football-card-game", "product"],
  ["aetherius-engineering-studio", "product"],
  ["IDE-Workspace", "product"],
  ["aetherion-engine", "engine"],
  ["genesis-layer", "engine"],
  ["Food Wiki App", "placeholder"],
]);

function readJson(path) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch {
    return null;
  }
}

function readYaml(path) {
  if (!existsSync(path)) return null;
  try {
    return parseYaml(readFileSync(path, "utf8"));
  } catch {
    return null;
  }
}

function number(env) {
  const value = Number(env);
  return Number.isFinite(value) ? value : 0;
}

const entries = [];

for (const dirName of readdirSync(APPS).sort()) {
  const dir = join(APPS, dirName);
  if (!statSync(dir).isDirectory()) continue;
  if (dirName === "node_modules") continue;

  const pkg = readJson(join(dir, "package.json"));
  const manifest = readYaml(join(dir, "build.yaml"));
  const project = manifest?.project ?? {};
  const status = manifest?.status ?? {};

  const hasSrc = existsSync(join(dir, "src"));
  const testFiles = existsSync(join(dir, "tests"))
    ? readdirSync(join(dir, "tests")).filter((file) => file.endsWith(".test.ts")).length
    : 0;

  const name = pkg?.name ?? null;
  const isAetherius = typeof name === "string" && name.startsWith("@aetherius/");
  const kind =
    KIND_BY_DIRECTORY.get(dirName) ??
    (isAetherius ? (project.kind === "library" ? "library" : "application") : "product");

  entries.push({
    directory: dirName,
    packageName: name,
    aetheriusSlice: isAetherius,
    id: project.id ?? pkg?.name ?? dirName,
    name: project.name ?? pkg?.name ?? dirName,
    kind,
    description: project.description ?? pkg?.description ?? null,
    // "UNSET" when the directory has no build.yaml status. The catalogue
    // must never silently drop a directory just because it is unmanifested.
    status: status.state ?? "UNSET",
    lastVerified: status.last_verified ?? null,
    hasSource: hasSrc,
    testFiles,
    testScript: pkg?.scripts?.test ?? null,
  });
}

// Code-unit order, not locale order. `localeCompare` depends on the host's
// ICU data and locale, so the Windows and Linux outputs diverged and the
// byte-identical catalogue test failed only in CI. This comparator is
// stable on every host Node runs on.
entries.sort((a, b) => (a.directory < b.directory ? -1 : a.directory > b.directory ? 1 : 0));

function js(value) {
  return JSON.stringify(value, null, 2);
}

const generated = `// GENERATED by scripts/generate-app-catalogue.mjs — do not hand-edit.
// Regenerate with: node scripts/generate-app-catalogue.mjs
//
// One entry per directory under apps/, including absorbed products
// (LedgerLands, Poietek, football-card-game) and engine stubs
// (aetherion-engine, genesis-layer), which are not @aetherius slices.
export interface CatalogueEntry {
  directory: string;
  packageName: string | null;
  aetheriusSlice: boolean;
  id: string;
  name: string;
  kind: "application" | "library" | "engine" | "product" | "placeholder";
  description: string | null;
  status: string | null;
  lastVerified: string | null;
  hasSource: boolean;
  testFiles: number;
  testScript: string | null;
}

export const APP_CATALOGUE: CatalogueEntry[] = ${js(entries)};

export function getCatalogueEntry(directory: string): CatalogueEntry | undefined {
  return APP_CATALOGUE.find((entry) => entry.directory === directory);
}

export function listAetheriusSlices(): CatalogueEntry[] {
  return APP_CATALOGUE.filter((entry) => entry.aetheriusSlice);
}
`;

if (process.argv.includes("--stdout")) {
  process.stdout.write(generated);
} else {
  writeFileSync(OUTPUT, generated, "utf8");
  console.log(`wrote ${OUTPUT.replace(root, ".")}`);
  console.log(`entries: ${entries.length}`);
  console.log(`  @aetherius slices: ${entries.filter((e) => e.aetheriusSlice).length}`);
  console.log(`  products: ${entries.filter((e) => e.kind === "product").length}`);
  console.log(`  engines: ${entries.filter((e) => e.kind === "engine").length}`);
  console.log(`  placeholders: ${entries.filter((e) => e.kind === "placeholder").length}`);
}
