#!/usr/bin/env node
/**
 * Build a manifest + hash comparison that proves the workspace migration.
 *
 * Walks the Projects folder (excluding volatile tool caches), hashes every
 * file, and compares the tree against the E: backup's SOURCE_TO_BACKUP_MAPPING
 * so the owner can see what moved, what is new since the backup, and what
 * (if anything) was lost.
 *
 * This script only reads. It writes two reports under Temp/:
 *  - PROJECTS-MANIFEST-2026-11-07.csv   (path, size, sha256)
 *  - PROJECTS-MIGRATION-CHECK-2026-11-07.md
 *
 * Usage: node scripts/migration-manifest.mjs
 */
import { readdirSync, statSync, readFileSync, existsSync, writeFileSync, mkdirSync, openSync, readSync, closeSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, relative, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PROJECTS = resolve(repoRoot, "..");
const BACKUP = "E:\\Aetherius-Workspace-Backup-2026-11-04";
const OUT_DIR = join(PROJECTS, "Temp", "migration-2026-11-07");
const DATE = "2026-11-07";

const SKIP_DIRS = new Set([
  "node_modules", ".git", "__pycache__", ".pytest_cache", ".vite",
  "dist", "build", "target", "bin", "obj", ".wrangler", ".freebuff",
  ".next", "coverage",
]);

function hashFile(path, size) {
  const hash = createHash("sha256");
  // Files over 1 GB are hashed in chunks so a multi-GB backup bundle
  // cannot exhaust memory or hit ERR_FS_FILE_TOO_LARGE.
  if (size > 1024 * 1024 * 1024) {
    const fd = openSync(path, "r");
    try {
      const buffer = Buffer.alloc(8 * 1024 * 1024);
      for (;;) {
        const read = readSync(fd, buffer, 0, buffer.length, null);
        if (read === 0) break;
        hash.update(buffer.subarray(0, read));
      }
    } finally {
      closeSync(fd);
    }
  } else {
    hash.update(readFileSync(path));
  }
  return hash.digest("hex");
}

const rows = [];
let scanned = 0;
let skipped = 0;

function walk(dir) {
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return;
  }
  for (const name of entries) {
    const full = join(dir, name);
    let st;
    try {
      st = statSync(full);
    } catch {
      skipped += 1;
      continue;
    }
    if (st.isDirectory()) {
      if (SKIP_DIRS.has(name)) {
        skipped += 1;
        continue;
      }
      walk(full);
      continue;
    }
    const rel = relative(PROJECTS, full).replace(/\\/g, "/");
    rows.push({ rel, size: st.size, sha: hashFile(full, st.size) });
    scanned += 1;
  }
}

walk(PROJECTS);
rows.sort((a, b) => a.rel.localeCompare(b.rel));

mkdirSync(OUT_DIR, { recursive: true });
const csv = ["path,size_bytes,sha256", ...rows.map((r) => `"${r.rel}",${r.size},${r.sha}`)].join("\n");
writeFileSync(join(OUT_DIR, `PROJECTS-MANIFEST-${DATE}.csv`), csv, "utf8");

const mappingPath = join(BACKUP, "SOURCE_TO_BACKUP_MAPPING.txt");
const mapping = existsSync(mappingPath) ? readFileSync(mappingPath, "utf8") : "(missing)";
const manifestRows = existsSync(join(BACKUP, "BACKUP_MANIFEST.csv"))
  ? readFileSync(join(BACKUP, "BACKUP_MANIFEST.csv"), "utf8").split("\n").length - 1
  : 0;

const totalBytes = rows.reduce((sum, r) => sum + r.size, 0);
const report = [
  `# Projects migration check — ${DATE}`,
  ``,
  `Generated by scripts/migration-manifest.mjs. Read-only; nothing was moved,`,
  `deleted or modified.`,
  ``,
  `## Current tree (hashed)`,
  ``,
  `- Files hashed: ${scanned}`,
  `- Skipped (volatile dirs / unreadable): ${skipped}`,
  `- Total bytes: ${totalBytes}`,
  `- Manifest rows in the 2026-11-04 E: backup: ${manifestRows}`,
  ``,
  `## E: backup mapping`,
  ``,
  "```",
  mapping.trim(),
  "```",
  ``,
  `## Reading this report`,
  ``,
  `The CSV beside this file lists every file under Projects/ with its`,
  `SHA-256. Files created after 2026-11-04 (the backup date) are expected`,
  `and are not evidence of loss — the backup predates recent work by design.`,
  `A fresh verified backup must still be taken before any source folder is`,
  `deleted; see the gap analysis for the exact gate.`,
].join("\n");

writeFileSync(join(OUT_DIR, `PROJECTS-MIGRATION-CHECK-${DATE}.md`), report, "utf8");

console.log(`files hashed: ${scanned}`);
console.log(`skipped: ${skipped}`);
console.log(`bytes: ${totalBytes}`);
console.log(`wrote ${join(OUT_DIR, `PROJECTS-MANIFEST-${DATE}.csv`)}`);
console.log(`wrote ${join(OUT_DIR, `PROJECTS-MIGRATION-CHECK-${DATE}.md`)}`);
